func TestIssueWebhookSubmitsTrustedMetadataWithoutToken(t *testing.T) {
	var tokenCalls int
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if strings.Contains(r.URL.Path, "/access_tokens") {
			tokenCalls++
		}
		http.Error(w, "unexpected GitHub request", http.StatusInternalServerError)
	}))
	defer server.Close()
	submitter := &recordingTaskSubmitter{}
	h := &Handler{
		github:    newTestManager(t, server.URL),
		submitter: submitter,
		triggers:  staticTriggerResolver{issue: []ReviewTrigger{{Name: "triage", Event: "opened"}}},
	}
	body := []byte(`{
		"action":"opened",
		"installation":{"id":222},
		"repository":{"full_name":"base/repo"},
		"issue":{"number":7,"title":"bug","body":"details","html_url":"https://github.com/base/repo/issues/7"}
	}`)
	if err := h.handleIssues(body, "delivery-issue"); err != nil {
		t.Fatal(err)
	}
	if len(submitter.tasks) != 1 {
		t.Fatalf("submitted tasks = %d, want 1", len(submitter.tasks))
	}
	req := submitter.tasks[0]
	if req.GitHubRepo != "base/repo" || req.GitHubInstallationID != 222 {
		t.Fatalf("task GitHub metadata = %q/%d", req.GitHubRepo, req.GitHubInstallationID)
	}
	if _, ok := req.Env["GITHUB_TOKEN"]; ok {
		t.Fatal("webhook task environment contains GITHUB_TOKEN")
	}
	if tokenCalls != 0 {
		t.Fatalf("installation token exchanges = %d, want 0", tokenCalls)
	}
}

func TestPullRequestWebhookRoutesAPICallsAndPinsBaseRepo(t *testing.T) {
	var tokenCalls int
	var authenticatedPaths []string
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch r.URL.Path {
		case "/app":
			_, _ = w.Write([]byte(`{"slug":"chetterbot"}`))
		case "/app/installations/222/access_tokens":
			tokenCalls++
			writeTokenResponse(w, "token-222")
		case "/repos/base/repo/issues/9/labels":
			if r.Header.Get("Authorization") != "Bearer token-222" {
				t.Errorf("authorization = %q", r.Header.Get("Authorization"))
			}
			authenticatedPaths = append(authenticatedPaths, r.Method+" "+r.URL.Path)
			if r.Method == http.MethodGet {
				_, _ = w.Write([]byte(`[]`))
				return
			}
			w.WriteHeader(http.StatusOK)
		default:
			http.NotFound(w, r)
		}
	}))
	defer server.Close()
	submitter := &recordingTaskSubmitter{}
	h := &Handler{
		github:    newTestManager(t, server.URL),
		submitter: submitter,
		triggers:  staticTriggerResolver{pr: []ReviewTrigger{{Name: "review", TriggerType: "pr_review"}}},
	}
	body := []byte(`{
		"action":"opened",
		"number":9,
		"installation":{"id":222},
		"repository":{"full_name":"base/repo"},
		"pull_request":{
			"number":9,
			"user":{"login":"chetterbot[bot]"},
			"base":{"ref":"main","repo":{"full_name":"base/repo"}},
			"head":{"ref":"feature","repo":{"full_name":"fork/repo","clone_url":"https://github.com/fork/repo.git"}}
		}
	}`)
	if err := h.handlePullRequest(body, "delivery-pr"); err != nil {
		t.Fatal(err)
	}
	if tokenCalls != 1 || len(authenticatedPaths) != 2 {
		t.Fatalf("token calls=%d authenticated paths=%v", tokenCalls, authenticatedPaths)
	}
	if len(submitter.reviews) != 1 {
		t.Fatalf("submitted reviews = %d, want 1", len(submitter.reviews))
	}
	review := submitter.reviews[0]
	if review.Repo != "base/repo" || review.GitHubInstallationID != 222 {
		t.Fatalf("review metadata = %q/%d", review.Repo, review.GitHubInstallationID)
	}
	if review.HeadCloneURL != "https://github.com/fork/repo.git" {
		t.Fatalf("head clone URL = %q", review.HeadCloneURL)
	}
}

