// so the agent knows which PR to review and how to post the review.
func TestBuildReviewTaskRequest_CustomPromptGetsContextBlock(t *testing.T) {
	review := ReviewContext{
		Trigger:              "opened",
		Repo:                 "flatout-works/chetter",
		PRNumber:             190,
		BaseRef:              "main",
		HeadRef:              "fix/runner-completion-detection",
		HeadCloneURL:         "https://github.com/flatout-works/chetter.git",
		GitHubInstallationID: 321,
		Prompt:               "You are doing a PR review for an opened PR.",
		Agent:                "pr-reviewer",
		ProviderID:           "opencode",
		ModelID:              "deepseek-v4-flash-free",
		TimeoutSec:           3600,
	}
	req := buildReviewTaskRequest(review)

	if !strings.HasPrefix(req.Prompt, "You are doing a PR review for an opened PR.") {
		t.Fatalf("Prompt should start with the custom trigger prompt, got: %q", req.Prompt[:80])
	}
	for _, want := range []string{
		"PR number: 190",
		"flatout-works/chetter",
		"fix/runner-completion-detection",
		"gh pr diff $PR_NUMBER",
		"chetter_pr_review",
	} {
		if !strings.Contains(req.Prompt, want) {
			t.Errorf("Prompt should contain %q, got prompt with %d chars", want, len(req.Prompt))
		}
	}
}

// TestAsyncCtxDoesNotLeakGoroutine is a regression test for issue #52. The old
// asyncCtx spawned a goroutine per call that blocked for the full timeout
// duration before calling cancel (a no-op). A burst of webhook events would
// therefore accumulate one idle goroutine per event. After the fix, asyncCtx
// allocates only a deadline context (with an internal timer, no goroutine), so
// the goroutine count must not grow with the number of calls.
func TestAsyncCtxDoesNotLeakGoroutine(t *testing.T) {
	// Force any prior GC/runtime noise to settle and snapshot a baseline.
	runtime.GC()
	before := runtime.NumGoroutine()

	const calls = 200
	for i := 0; i < calls; i++ {
		_ = asyncCtx(500 * time.Millisecond)
	}

	after := runtime.NumGoroutine()
	// The old implementation would have added ~200 idle goroutines here. Allow a
	// small margin for unrelated runtime/test scheduler goroutines.
	if after > before+8 {
		t.Fatalf("asyncCtx leaked goroutines: before=%d after=%d (expected ~%d)", before, after, before)
	}

	// The returned contexts must still be valid, deadline-bounded contexts.
	ctx := asyncCtx(50 * time.Millisecond)
	select {
	case <-ctx.Done():
	case <-time.After(time.Second):
		t.Fatal("asyncCtx context did not expire by its deadline")
	}
	if err := ctx.Err(); err != context.DeadlineExceeded {
		t.Fatalf("ctx.Err() = %v, want DeadlineExceeded", err)
	}
}

// TestHandlerShutdownWaitsForInflightGoroutines is a regression test for issue
// #57. Shutdown must block until all in-flight handle() goroutines finish, so
// the server does not close the database while webhook events are still being
// processed.
func TestHandlerShutdownWaitsForInflightGoroutines(t *testing.T) {
	h := &Handler{}

	// Simulate an in-flight goroutine that takes 50ms.
	h.wg.Add(1)
	start := time.Now()
	go func() {
		defer h.wg.Done()
		time.Sleep(50 * time.Millisecond)
	}()

	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
	defer cancel()
	if err := h.Shutdown(ctx); err != nil {
		t.Fatalf("Shutdown returned error: %v", err)
	}
	elapsed := time.Since(start)
	if elapsed < 40*time.Millisecond {
		t.Fatalf("Shutdown returned before goroutine finished, elapsed=%v", elapsed)
	}
}

// TestHandlerShutdownTimesOut verifies that Shutdown returns ctx.Err() when
// in-flight goroutines exceed the deadline, rather than blocking forever. See
// issue #57 acceptance criteria.
func TestHandlerShutdownTimesOut(t *testing.T) {
	h := &Handler{}

	// Simulate a long-running goroutine that never finishes within the drain.
	h.wg.Add(1)
	go func() {
		defer h.wg.Done()
		time.Sleep(10 * time.Second)
	}()

	ctx, cancel := context.WithTimeout(context.Background(), 50*time.Millisecond)
	defer cancel()
	err := h.Shutdown(ctx)
	if err == nil {
		t.Fatal("Shutdown should have timed out, but returned nil")
	}
}
